#!/usr/bin/env python3
"""Generate or check THIRD_PARTY_NOTICES.txt from the locked license sources.

The notices file is what a binary distribution of wui must carry: wui's own
license, then the full license text of every library and font linked into
or shipped with it. doctest is test-only and is never distributed, so it is
not listed. Sources come from the prepared checkouts; this tool never
fetches anything.
"""

from __future__ import annotations

import argparse
import difflib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "THIRD_PARTY_NOTICES.txt"


def sections() -> list[tuple[str, str, str, Path, str]]:
    lock = json.loads((ROOT / "third_party" / "lock.json").read_text(encoding="utf-8"))
    deps = {item["name"]: item for item in lock["dependencies"]}
    fonts = lock["fonts"]
    project = re.search(r"project\(wui VERSION (\S+)", (ROOT / "CMakeLists.txt").read_text(encoding="utf-8"))
    if not project:
        raise SystemExit("error: CMakeLists.txt has no project(wui VERSION ...)")
    return [
        ("wui", project.group(1), "MIT", ROOT / "LICENSE", ""),
        ("FreeType", deps["freetype"]["version"], "FTL", ROOT / "third_party/freetype/docs/FTL.TXT",
         "FreeType is dual-licensed (third_party/freetype/LICENSE.TXT); wui uses it under the\n"
         "FreeType License (FTL) alternative, reproduced below.\n\n"),
        ("HarfBuzz", deps["harfbuzz"]["version"], deps["harfbuzz"]["license"],
         ROOT / "third_party/harfbuzz/COPYING", ""),
        ("utf8proc", deps["utf8proc"]["version"], deps["utf8proc"]["license"],
         ROOT / "third_party/utf8proc/LICENSE.md", ""),
        ("Inter", fonts["version"], "SIL OFL 1.1", ROOT / "assets/fonts/LICENSE.txt",
         "Inter-Regular.ttf and Inter-SemiBold.ttf are distributed under this license.\n\n"),
    ]


def render() -> str:
    parts = ["Third-party notices for wui\n",
             "This file lists wui's license and the licenses of every library and font\n"
             "that a wui binary links or ships. Generated by tools/collect_notices.py.\n"]
    for name, version, license_name, path, preamble in sections():
        if not path.exists():
            raise SystemExit(f"error: missing license source {path.relative_to(ROOT).as_posix()}; "
                             "run tools/prepare_dependencies.py --fetch explicitly")
        text = path.read_text(encoding="utf-8", errors="strict").replace("\r\n", "\n").rstrip("\n")
        parts.append(f"\n== {name} {version} ({license_name}) ==\n\n{preamble}{text}\n")
    return "".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.write:
        OUTPUT.write_bytes(expected.encode("utf-8"))
        print(f"wrote {OUTPUT.relative_to(ROOT).as_posix()}")
        return 0
    actual = OUTPUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUTPUT.exists() else ""
    if actual == expected:
        print("notices up to date")
        return 0
    diff = list(difflib.unified_diff(actual.splitlines(), expected.splitlines(), "committed", "expected",
                                     lineterm="", n=1))
    print(f"THIRD_PARTY_NOTICES.txt is stale ({len(diff)} diff lines); run tools/collect_notices.py --write")
    print("\n".join(diff[:20]))
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
